import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
const base=join(dirname(fileURLToPath(import.meta.url)),'..');
const source=readFileSync(join(base,'pdf-engine.js'),'utf8');
const html=readFileSync(join(base,'index.html'),'utf8');
const app=readFileSync(join(base,'app.js'),'utf8');
assert.match(source,/getAutomaticUnicodeFonts/);
assert.doesNotMatch(source,/pdf\.embedFont\(StandardFonts\.TimesRomanBold/);
assert.doesNotMatch(source,/tidak didukung Times bawaan/);
assert.match(source,/Set\(bold\.getCharacterSet\(\)\)/);
assert.match(source,/subset:true/);
assert.match(source,/Font Unicode/);
assert.match(html,/V4\.14/);
assert.match(html,/Tinos/);
assert.match(app,/Font Unicode Tinos otomatis/);
let hits=[];
const bytes=new Uint8Array(16000);
bytes[0]=0;bytes[1]=1;bytes[2]=0;bytes[3]=0;
globalThis.fetch=async(url)=>{
 hits.push(String(url));
 return {ok:true,arrayBuffer:async()=>bytes.buffer};
};
const {getAutomaticUnicodeFonts,__test}=await import('../font-unicode.js');
assert.equal(__test.isFont(bytes),true);
assert.equal(__test.isFont(new Uint8Array(2)),false);
assert.ok(__test.sourceCount('bold')>=2);
const first=await getAutomaticUnicodeFonts();
assert.ok(first.bold.length>=12000);
assert.ok(first.italic.length>=12000);
const second=await getAutomaticUnicodeFonts();
assert.equal(first.bold,second.bold);
assert.equal(first.italic,second.italic);
assert.equal(hits.length,2,'kedua font hanya diunduh satu kali');
const quote='ANALISIS “KARTINI NYANTRI” Maqāṣid al-Syarī‘ah';
assert.ok(quote.includes('\u201c')&&quote.includes('\u201d'));
assert.ok(quote.includes('ā')&&quote.includes('ī'));
console.log('PASS: source memakai font Unicode otomatis; bentuk teks dan italic tetap disimpan; 1 fetch per gaya font pada test mock.');
